  assert.equal(await tooltip.evaluate(e=>getComputedStyle(e).textOverflow),'ellipsis');
  assert((await popup.evaluate(()=>window.messages)).includes('popup:size:360 36'));
  assert.equal(await popup.locator('#island').evaluate(e=>getComputedStyle(e).backgroundColor),'rgba(0, 0, 0, 0)');
